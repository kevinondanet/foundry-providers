using InspectAzureAI.Eval.Context;
using InspectAzureAI.Eval.Scorers;

namespace InspectAzureAI.Eval.Agents.Human;

/// <summary>Port of <c>agent/_human/state.py</c> <c>IntermediateScoring</c>: one <c>task score</c> result and the task time it was taken at.</summary>
public sealed record IntermediateScoring(double Time, IReadOnlyList<Score> Scores);

/// <summary>
/// Port of <c>agent/_human/state.py</c> <c>HumanAgentState</c>: the human agent's progress kept in the sample
/// store (keys <c>HumanAgentState:instructions</c>, <c>:running_state</c>, <c>:started_running</c>,
/// <c>:accumulated_time</c>, <c>:scorings</c>, <c>:answer</c>, <c>:logs</c>), with the clock arithmetic of the
/// <c>running</c> and <c>time</c> properties. Deviation: <c>running</c> and <c>time</c> are the methods
/// <see cref="IsRunning"/>, <see cref="SetRunning"/> and <see cref="Time"/> so the store model's field set stays
/// exactly Python's; the wall clock is unix seconds and can be replaced per async flow for tests.
/// </summary>
public sealed class HumanAgentState : StoreModel
{
    /// <summary>A replacement for <c>time.time()</c> in the current async flow (tests); null uses the wall clock.</summary>
    internal static readonly AsyncLocal<Func<double>?> ClockOverride = new();

    private readonly Func<double> _clock = ClockOverride.Value ?? UnixTime;

    /// <summary>Task instructions.</summary>
    public string Instructions
    {
        get => Get("");
        set => Set(value);
    }

    /// <summary>Intermediate scorings yielded by <c>task score</c>.</summary>
    public IReadOnlyList<IntermediateScoring> Scorings
    {
        get => Get<IReadOnlyList<IntermediateScoring>>([]);
        set => Set(value);
    }

    /// <summary>Final answer provided in <c>task submit</c> (an empty string after <c>task quit</c>; null while working).</summary>
    public string? Answer
    {
        get => Get<string?>(null);
        set => Set(value);
    }

    /// <summary>Session logs generated by <c>script</c>, keyed by file name.</summary>
    public IReadOnlyDictionary<string, string> Logs
    {
        get => Get<IReadOnlyDictionary<string, string>>(new Dictionary<string, string>(StringComparer.Ordinal));
        set => Set(value);
    }

    /// <summary>Internal state variable of the running/time arithmetic (Python <c>running_state</c>).</summary>
    public bool RunningState
    {
        get => Get(false);
        set => Set(value);
    }

    /// <summary>Internal state variable: unix time the clock last started (Python <c>started_running</c>).</summary>
    public double StartedRunning
    {
        get => Get(_clock());
        set => Set(value);
    }

    /// <summary>Internal state variable: seconds accumulated before the current run (Python <c>accumulated_time</c>).</summary>
    public double AccumulatedTime
    {
        get => Get(0.0);
        set => Set(value);
    }

    /// <summary>Port of the <c>running</c> getter: is the task clock running?</summary>
    public bool IsRunning() => RunningState;

    /// <summary>
    /// Port of the <c>running</c> setter: flipping to running records the start time; leaving running mode folds
    /// the elapsed run into <see cref="AccumulatedTime"/>.
    /// </summary>
    public void SetRunning(bool running)
    {
        var current = RunningState;
        if (!current && running)
        {
            StartedRunning = _clock();
        }

        if (current && !running)
        {
            AccumulatedTime = Time();
        }

        RunningState = running;
    }

    /// <summary>Port of the <c>time</c> property: total seconds spent on the task (accumulated plus the current run).</summary>
    public double Time()
    {
        var runningTime = RunningState ? _clock() - StartedRunning : 0.0;
        return AccumulatedTime + runningTime;
    }

    private static double UnixTime() => DateTimeOffset.UtcNow.ToUnixTimeMilliseconds() / 1000.0;
}
